USE superstore_db;

-- ---------- 1. Load raw CSV into staging ----------
TRUNCATE TABLE stg_orders;

LOAD DATA LOCAL INFILE 'data/superstore_raw.csv'
INTO TABLE stg_orders
CHARACTER SET utf8mb4
FIELDS TERMINATED BY ',' OPTIONALLY ENCLOSED BY '"'
LINES TERMINATED BY '\n'
IGNORE 1 LINES
(row_id, order_id, order_date, ship_date, ship_mode, customer_id, customer_name,
 segment, country, city, state, postal_code, region, product_id, category,
 sub_category, product_name, sales, quantity, discount, profit);

-- ---------- 2. Data quality checks (each should match the expected result) ----------

-- 2a. Row count  -> expected 9994
SELECT COUNT(*) AS total_rows FROM stg_orders;

-- 2b. Missing values in key columns -> expected 0
SELECT
    SUM(order_id    IS NULL OR order_id    = '') AS missing_order_id,
    SUM(customer_id IS NULL OR customer_id = '') AS missing_customer_id,
    SUM(product_id  IS NULL OR product_id  = '') AS missing_product_id,
    SUM(postal_code IS NULL OR postal_code = '') AS missing_postal_code,
    SUM(sales IS NULL)                           AS missing_sales
FROM stg_orders;

-- 2c. Possible duplicate order lines
--     Finding: 1 line (order US-2014-150119, a leather chair) appears twice with different Row IDs.
--     Decision: kept both, because the same product can legitimately be entered twice on one order;
--     flagged here for the business to confirm.
SELECT order_id, product_id, product_name, sales, quantity, COUNT(*) AS copies
FROM stg_orders
GROUP BY order_id, product_id, product_name, sales, quantity
HAVING COUNT(*) > 1;

-- 2d. Invalid values -> expected 0
SELECT
    SUM(sales <= 0)                 AS non_positive_sales,
    SUM(quantity <= 0)              AS non_positive_qty,
    SUM(discount < 0 OR discount > 1) AS invalid_discount,
    SUM(ship_date < order_date)     AS shipped_before_ordered
FROM stg_orders;

-- 2e. Product IDs that point to more than one product name (data quality issue found)
SELECT product_id, COUNT(DISTINCT product_name) AS name_count
FROM stg_orders
GROUP BY product_id
HAVING COUNT(DISTINCT product_name) > 1
ORDER BY product_id;

-- 2f. Tidy text: trim stray spaces
UPDATE stg_orders
SET customer_name = TRIM(customer_name),
    product_name  = TRIM(product_name),
    city          = TRIM(city);

-- ---------- 3. Build dimensions ----------

-- 3a. Continuous date dimension covering every order and ship date
--     (numbers 0-9999 generated by cross-joining digits; no recursion needed)
INSERT INTO dim_date (date_key, full_date, year_num, quarter_num, month_num, month_name, day_name)
SELECT
    CAST(DATE_FORMAT(d.dt, '%Y%m%d') AS UNSIGNED),
    d.dt, YEAR(d.dt), QUARTER(d.dt), MONTH(d.dt), MONTHNAME(d.dt), DAYNAME(d.dt)
FROM (
    SELECT DATE_ADD(b.start_date, INTERVAL n.num DAY) AS dt, b.end_date
    FROM (SELECT MIN(order_date) AS start_date, MAX(ship_date) AS end_date FROM stg_orders) b
    CROSS JOIN (
        SELECT a.i + 10*b.i + 100*c.i + 1000*d.i AS num
        FROM (SELECT 0 i UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4
              UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9) a
        CROSS JOIN (SELECT 0 i UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4
              UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9) b
        CROSS JOIN (SELECT 0 i UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4
              UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9) c
        CROSS JOIN (SELECT 0 i UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4
              UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9) d
    ) n
) d
WHERE d.dt <= d.end_date;

-- 3b. Customers (one row per customer ID)
INSERT INTO dim_customer (customer_id, customer_name, segment)
SELECT customer_id, MIN(customer_name), MIN(segment)
FROM stg_orders
GROUP BY customer_id;

-- 3c. Products (surrogate key handles the duplicate product IDs)
INSERT INTO dim_product (product_id, product_name, category, sub_category)
SELECT product_id, product_name, MIN(category), MIN(sub_category)
FROM stg_orders
GROUP BY product_id, product_name;

-- 3d. Locations
INSERT INTO dim_location (country, region, state, city, postal_code)
SELECT MIN(country), MIN(region), state, city, postal_code
FROM stg_orders
GROUP BY state, city, postal_code;

-- ---------- 4. Build fact table ----------
INSERT INTO fact_sales (sales_line_id, order_id, order_date_key, ship_date_key, ship_mode,
                        customer_key, product_key, location_key,
                        sales, quantity, discount, profit, days_to_ship)
SELECT
    s.row_id,
    s.order_id,
    CAST(DATE_FORMAT(s.order_date, '%Y%m%d') AS UNSIGNED),
    CAST(DATE_FORMAT(s.ship_date,  '%Y%m%d') AS UNSIGNED),
    s.ship_mode,
    c.customer_key,
    p.product_key,
    l.location_key,
    s.sales, s.quantity, s.discount, s.profit,
    DATEDIFF(s.ship_date, s.order_date)
FROM stg_orders s
JOIN dim_customer c ON c.customer_id = s.customer_id
JOIN dim_product  p ON p.product_id  = s.product_id AND p.product_name = s.product_name
JOIN dim_location l ON l.state = s.state AND l.city = s.city AND l.postal_code = s.postal_code;

-- ---------- 5. Reconcile: fact must match staging exactly ----------
SELECT 'staging' AS source, COUNT(*) AS line_count, ROUND(SUM(sales), 2) AS total_sales, ROUND(SUM(profit), 2) AS total_profit FROM stg_orders
UNION ALL
SELECT 'fact', COUNT(*), ROUND(SUM(sales), 2), ROUND(SUM(profit), 2) FROM fact_sales;

SELECT
    (SELECT COUNT(*) FROM dim_date)     AS dates,
    (SELECT COUNT(*) FROM dim_customer) AS customers,
    (SELECT COUNT(*) FROM dim_product)  AS products,
    (SELECT COUNT(*) FROM dim_location) AS locations;
